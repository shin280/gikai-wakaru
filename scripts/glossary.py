def slug(term: str) -> str:
    return "t" + str([t[0] for t in TERMS].index(term))


def found_in(text: str) -> list[tuple]:
    out = []
    for t in TERMS:
        words = [t[0].split("（")[0]] + t[4]
        if any(w in text for w in words):
            out.append(t)
    return out
