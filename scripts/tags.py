FIELDS = {
    "子育て・教育": ["保育", "児童", "幼稚園", "学校", "教育", "子ども", "乳児", "教職員", "図書館", "通園"],
    "福祉・医療": ["介護", "高齢", "病院", "医療", "補聴器", "福祉", "国民健康保険", "後期高齢者", "障がい", "障害", "生活保護", "OTC"],
    "防災・消防": ["消防", "救急", "防災", "災害", "胸骨圧迫"],
    "まちづくり・道路": ["市道", "景観", "都市計画", "道路", "公園", "下水道", "区画整理", "交通", "かなちゃんパス"],
    "環境・ごみ": ["廃棄物", "ごみ", "環境", "リサイクル"],
    "産業・農業": ["農業", "中小企業", "商工", "競輪", "卸売市場", "漁業", "観光", "事業者"],
    "施設・工事": ["公民館", "体育館", "工事", "庁舎", "改修"],
    "予算・決算": ["補正予算", "予算", "決算", "利益の処分", "継続費", "繰越"],
    "人事・表彰": ["任命", "選任", "推薦", "表彰", "名誉市民"],
    "議会・行政のしくみ": ["議会", "行政手続", "附属機関", "手当", "印鑑", "マイナンバー", "個人を識別"],
}


def tags_for(text: str) -> dict:
    fields = [f for f, words in FIELDS.items() if any(w in text for w in words)]
    areas = sorted({m for m in re.findall(r"([一-龥ァ-ヶー]{1,4})公民館", text) if m not in ("中央", "新中央", "各")})
    if "夕陽ケ丘" in text:
        areas.append("夕陽ケ丘")
    return {"fields": fields, "areas": areas}
